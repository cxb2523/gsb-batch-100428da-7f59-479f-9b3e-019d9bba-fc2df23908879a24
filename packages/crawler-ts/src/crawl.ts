type ValueOrPromise<T> = T | Promise<T>;

export interface Logger {
  info: (...args: any[]) => void;
  error: (...args: any[]) => void;
}

export interface PreParseProps<L, R> {
  location: L;
  response: R;
}

export interface PostParseProps<L, R, P> extends PreParseProps<L, R> {
  parsed: P;
}

/**
 * The outcome of visiting a single location.
 *
 * - `yielded`: the location was parsed and yielded a result.
 * - `skipped`: the location did not pass `shouldParse` (or no response was returned) or did not pass `shouldYield`.
 * - `unparsed`: the `parser` returned an empty result.
 * - `failed`: the `requester`, `shouldParse` or `parser` threw an error.
 */
export type VisitOutcome = 'yielded' | 'skipped' | 'unparsed' | 'failed';

/**
 * @type {L} The type of the locations to crawl.
 * @type {R} The type of the response at the location that is crawled.
 * @type {P} The intermediate parsed result that can be parsed from the response and generated by the crawler.
 */
export interface VisitProps<L, R, P> {
  /**
   * The location that was visited.
   */
  location: L;
  /**
   * The location that this location was followed from, or `undefined` for the start location.
   */
  origin: L | undefined;
  /**
   * The outcome of the visit.
   */
  outcome: VisitOutcome;
  /**
   * The response, if it was obtained.
   */
  response?: R;
  /**
   * The parsed result, if it was obtained.
   */
  parsed?: P;
  /**
   * The error that caused the visit to fail, if `outcome` is `'failed'`.
   */
  error?: unknown;
}

export type OnVisit<L, R, P> = (props: VisitProps<L, R, P>) => ValueOrPromise<void>;

/**
 * @type {L} The type of the locations to crawl, e.g. `URL` or `string` that represents a path.
 * @type {R} The type of the response at the location that is crawler, e.g. Cheerio object, file system `fs.Stats`.
 * @type {P} The intermediate parsed result that can be parsed from the response and generated by the crawler.
 */
export interface Options<L, R, P> {
  /**
   * This function should return the response for the given location.
   */
  requester(location: L): ValueOrPromise<R | undefined>;
  /**
   * This function should return true if the crawler should parse the response, or false if not.
   */
  shouldParse(props: PreParseProps<L, R>): ValueOrPromise<boolean>;
  /**
   * This function should parse the response and convert the response to the parsed type.
   */
  parser(props: PreParseProps<L, R>): ValueOrPromise<P | undefined>;
  /**
   * This function should return true if the crawler should yield the parsed result, or false if not.
   */
  shouldYield(props: PostParseProps<L, R, P>): ValueOrPromise<boolean>;
  /**
   * This function should yield all the locations to follow in the given parsed result.
   */
  follower(props: PostParseProps<L, R, P>): AsyncGenerator<L>;
  /**
   * This function should return true if the crawler should queue the location for crawling, or false if not.
   */
  shouldQueue(props: { location: L; origin: L; response: R; parsed: P }): ValueOrPromise<boolean>;
  /**
   * This function is called once for every visited location, with the outcome of the visit.
   *
   * Errors thrown by this function are logged and do not interrupt the crawl.
   *
   * @default undefined
   */
  onVisit?: OnVisit<L, R, P>;
  /**
   * The logger can be set to `console` to output debug information to the `console`.
   *
   * @default undefined
   */
  logger?: Logger;
}

export function createCrawler<L, R, P>(
  options: Options<L, R, P>,
): (start: L) => AsyncGenerator<PostParseProps<L, R, P>> {
  const { requester, shouldParse, parser, shouldYield, follower, shouldQueue, onVisit, logger } = options;

  async function report(
    location: L,
    origin: L | undefined,
    props: Omit<VisitProps<L, R, P>, 'location' | 'origin'>,
  ): Promise<void> {
    if (!onVisit) {
      return;
    }
    try {
      await onVisit({ location, origin, ...props });
    } catch (e) {
      logger?.error(`Cannot report visit of ${location}`);
      logger?.error(e);
    }
  }

  async function* gen(location: L, origin: L | undefined): AsyncGenerator<PostParseProps<L, R, P>> {
    let response: R | undefined;
    let parsed: P | undefined;
    let reported = false;
    try {
      logger?.info(`Requesting ${location}`);
      response = await requester(location);
      if (response) {
        if (!(await shouldParse({ location, response }))) {
          reported = true;
          await report(location, origin, { outcome: 'skipped', response });
          return;
        }

        logger?.info(`Parsing ${location}`);
        parsed = await parser({ location, response });
        if (!parsed) {
          reported = true;
          await report(location, origin, { outcome: 'unparsed', response });
          return;
        }

        if (await shouldYield({ location, response, parsed })) {
          logger?.info(`Yielding ${location}`);
          reported = true;
          await report(location, origin, { outcome: 'yielded', response, parsed });
          yield { location, response, parsed };
        } else {
          reported = true;
          await report(location, origin, { outcome: 'skipped', response, parsed });
        }

        for await (const next of follower({ location, response, parsed })) {
          try {
            if (await shouldQueue({ location: next, origin: location, response, parsed })) {
              logger?.info(`Queueing ${next}`);
              yield* gen(next, location);
            }
          } catch (e) {
            logger?.error(`Cannot queue ${next}`);
            logger?.error(e);
          }
        }
      } else {
        reported = true;
        await report(location, origin, { outcome: 'skipped' });
      }
    } catch (e) {
      logger?.error(`Cannot visit ${location}`);
      logger?.error(e);
      if (!reported) {
        reported = true;
        await report(location, origin, { outcome: 'failed', response, parsed, error: e });
      }
    }
  }

  return (start: L) => gen(start, undefined);
}
